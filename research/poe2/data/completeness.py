"""Completeness pass: does every crafting item of PoE2 have a claim that names it?

Lists every name in the crafting groups of the official trade site's static list (the committed
snapshot `trade-api-2026-11-24/static.json`) and every item of class Omen in the pinned
`base_items.json`, then looks for each name in the text of `docs/poe2/claims/*.yaml` (a
statement, a quote or a value). Writes `docs/poe2/COMPLETENESS.md`. Standard library only.
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fetch_poe2 import cache_root, load_pin  # noqa: E402

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
CRAFTING_GROUPS = ["Currency", "Vaal", "Ritual", "Abyss", "Essences", "Runes", "Breach", "Delirium", "Verisium", "Expedition"]
NOT_CRAFTING = {
    "Ritual": {"Petition Splinter", "An Audience with the King", "Call of the Shadows", "Head of the King", "Sacred Bloom"},
    "Breach": {"Breach Splinter", "Breachstone"},
    "Delirium": {"Simulacrum Splinter", "Simulacrum"},
    "Expedition": {"Expedition Logbook"},
}
GROUP_HEADINGS = {"Omens", "Augments", "Idols", "Soul Cores", "Catalysts", "Liquid Emotions", "Flux"}


def main() -> int:
    static = json.loads((HERE / "trade-api-2026-11-24" / "static.json").read_text(encoding="utf-8"))["result"]
    names: dict[str, str] = {}
    for group in static:
        if group["id"] not in CRAFTING_GROUPS:
            continue
        for entry in group["entries"]:
            text = entry.get("text", "")
            if text and text not in GROUP_HEADINGS and text not in NOT_CRAFTING.get(group["id"], set()):
                names.setdefault(text, f"trade: {group['id']}")
    base_items = json.loads((cache_root() / load_pin()["version"] / "base_items.json").read_text(encoding="utf-8"))
    for record in base_items.values():
        if record["item_class"] == "Omen" and record["name"]:
            names.setdefault(record["name"], "game data: Omen")
    corpus = "\n".join(path.read_text(encoding="utf-8") for path in sorted((ROOT / "docs" / "poe2" / "claims").glob("*.yaml")))
    corpus = corpus.replace("’", "'")
    found, missing = [], []
    for name, origin in sorted(names.items(), key=lambda item: (item[1], item[0])):
        pattern = re.escape(name.replace("’", "'"))
        (found if re.search(pattern, corpus) else missing).append((name, origin))
    lines = [
        "# Completeness pass: every PoE2 crafting item against the claims",
        "",
        f"Generated by `research/poe2/data/completeness.py` on the claims in `docs/poe2/claims/` and PoE2 {load_pin()['version']}. "
        "The names are every entry of the crafting groups of the official trade site's list (`api/trade2/data/static`, read 2026-11-24: "
        + ", ".join(CRAFTING_GROUPS)
        + ") except group headings and non-crafting entries (splinters, Breachstone, Simulacrum, Ritual rewards, Logbook), and every item of class Omen in the game data. "
        "A name counts as covered when a claim's text (statement, quote or value) names it.",
        "",
        f"**{len(found)} of {len(names)} covered; {len(missing)} not named by any claim.**",
        "",
        "## Not named by any claim",
        "",
    ]
    lines += [f"- {name} ({origin})" for name, origin in missing] or ["None."]
    lines += ["", "## Covered", "", ", ".join(name for name, _ in found)]
    (ROOT / "docs" / "poe2" / "COMPLETENESS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(found)} of {len(names)} covered; missing: {[name for name, _ in missing]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
