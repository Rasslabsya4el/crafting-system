"""Turn the pinned PoE2 tables into readable Markdown extracts under `research/poe2/data/derived/`.

Reads the cache that `fetch_poe2.py fetch` fills (same `CRAFTING_CACHE_DIR` rule) and writes one
Markdown file per crafting table: tiered currency minimum levels, essences and their mods per item
category, abyss bones, socketables (runes, soul cores, idols, talismans), the Vaal temple benches,
recombinable classes, Verisium crafts, the currency exchange categories and a modifier census per
item class. Standard library only; run with `python -I`.

A column name that starts with a type (`i32_28`, `[rid]_96`, `bool_96`) is a column the
dat-schema has not named yet: its meaning is a guess and the extract says so.
"""

import ast
import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fetch_poe2 import cache_root, load_pin  # noqa: E402

csv.field_size_limit(1 << 30)
OUT = Path(__file__).resolve().parent / "derived"


def folder() -> Path:
    return cache_root() / load_pin()["version"]


def table(name: str) -> list[dict]:
    with (folder() / "dat" / f"{name}.csv").open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def ids(value: str) -> list[int]:
    value = (value or "").strip()
    if not value:
        return []
    parsed = ast.literal_eval(value)
    return list(parsed) if isinstance(parsed, (list, tuple)) else [parsed]


def one(value: str) -> int | None:
    found = ids(value)
    return found[0] if found else None


def cell(text: object) -> str:
    return str(text).replace("|", "/").replace("\n", " ").strip()


def write(name: str, title: str, intro: str, header: list[str], rows: list[list], tail: str = "") -> None:
    pin = load_pin()
    lines = [
        f"# {title}",
        "",
        f"Generated by `research/poe2/data/derive_tables.py` from PoE2 {pin['version']} "
        f"(repoe-fork/poe2 {pin['commit'][:8]}, repoe-fork/dat-export {pin['tables_source']['commit'][:8]}). "
        "Source kind for a claim citing a row: `datamined`.",
        "",
        intro,
        "",
        "| " + " | ".join(header) + " |",
        "|" + "---|" * len(header),
    ]
    lines += ["| " + " | ".join(cell(item) for item in row) + " |" for row in rows]
    if tail:
        lines += ["", tail]
    OUT.mkdir(exist_ok=True)
    (OUT / f"{name}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{name}: {len(rows)} rows")


def main() -> None:
    bases = table("BaseItemTypes")
    base_name = {int(row["rownum"]): row["Name"] or row["Id"] for row in bases}
    base_id = {int(row["rownum"]): row["Id"] for row in bases}
    classes = {int(row["rownum"]): row["Id"] for row in table("ItemClasses")}
    mods = table("Mods")
    mod_id = {int(row["rownum"]): row["Id"] for row in mods}
    repoe_mods = json.loads((folder() / "mods.json").read_text(encoding="utf-8"))

    def mod_text(row: int | None) -> str:
        if row is None:
            return ""
        key = mod_id.get(row, f"row {row}")
        record = repoe_mods.get(key, {})
        return f"{key}: {record.get('text', '')} (level {record.get('required_level', '?')}, {record.get('generation_type', '?')})"

    # 1. Tiered currency
    rows = []
    for row in table("TieredCurrency"):
        rows.append([base_name[int(row["BaseItemType"])], row["Tier"], row["MinimumModLevel"],
                     base_name[int(row["LowerTierBaseItemType"])]])
    write("tiered-currency", "Greater and Perfect currency: minimum modifier level",
          "Table `TieredCurrency`: each Greater (tier 2) and Perfect (tier 3) orb and the lowest modifier level it can add.",
          ["currency", "tier", "minimum modifier level", "lower tier"], rows)

    # 2. Essences
    categories = {int(row["rownum"]): (row["Id"], [classes.get(c, c) for c in ids(row["ItemClasses"])])
                  for row in table("EssenceTargetItemCategories")}
    essences = {int(row["rownum"]): row for row in table("Essences")}
    rows = []
    for row in table("EssenceMods"):
        essence = essences[int(row["Essence"])]
        category = categories.get(int(row["TargetItemCategory"]), (row["TargetItemCategory"], []))
        outcome = ", ".join(mod_id.get(m, str(m)) for m in ids(row["OutcomeMods"]))
        rows.append([base_name[int(essence["BaseItemType"])], essence["Tier"], essence["Perfect"] or "",
                     category[0], mod_text(one(row["Mod"])), outcome, row["OutcomeModWeights"]])
    rows.sort(key=lambda item: (item[0], item[3]))
    category_lines = "\n".join(f"- `{name}`: {', '.join(members)}" for name, members in categories.values())
    write("essences", "Essences: the guaranteed mod per item category",
          "Tables `Essences`, `EssenceMods`, `EssenceTargetItemCategories`. `tier` and `perfect` are the columns of `Essences`; "
          "`outcome mods` and `weights` are filled for essences whose result is drawn from a list (corrupted ones).",
          ["essence", "tier", "perfect", "item category", "guaranteed mod", "outcome mods", "weights"], rows,
          "## Item categories\n\n" + category_lines)

    # 3. Abyss bones
    rows = []
    for row in table("AbyssBenchTicketTypes"):
        rows.append([base_name[int(row["BaseItemType"])], ", ".join(classes.get(c, str(c)) for c in ids(row["UsableOnItemClasses"])),
                     row["MaximumItemLevel"], row["MinimumModLevel"], row["f32_48"], row["bool_52"], row["Tag"]])
    write("abyss-bones", "Abyss bones: what each one desecrates",
          "Table `AbyssBenchTicketTypes`. `f32_48` and `bool_52` are unnamed columns (guess: the chance and the flag of 'otherworldly' mods).",
          ["bone", "item classes", "maximum item level", "minimum modifier level", "f32_48", "bool_52", "tag"], rows)

    # 4. Socketables
    cores = table("SoulCores")
    stats = {int(row["rownum"]): row["Id"] for row in table("Stats")}
    categories_sc = {int(row["rownum"]): row.get("Id", row["rownum"]) for row in table("SoulCoreStatCategories")}
    per_core = defaultdict(list)
    for row in table("SoulCoreStats"):
        stat_list = ", ".join(f"{stats.get(s, s)}={v}" for s, v in zip(ids(row["Stats"]), ids(row["StatsValues"])))
        per_core[int(row["SoulCore"])].append(f"{categories_sc.get(int(row['StatCategory']), row['StatCategory'])}: {stat_list}")
    rows = []
    for row in cores:
        rows.append([base_name[int(row["BaseItemType"])], base_id[int(row["BaseItemType"])].split("/")[-1], row["RequiredLevel"],
                     row["Type"], row["CanSocketInMartialArtistSlots"], row["CanSocketInUniqueItems"], row["CanSocketInJewellery"],
                     row["CanSocketInCorruptedSanctified"], "; ".join(per_core[int(row["rownum"])])])
    write("socketables", "Socketables (runes, soul cores, talismans, idols): effect per item category",
          "Tables `SoulCores`, `SoulCoreStats`, `SoulCoreStatCategories`. The stat ids are the game's; the readable text is in "
          "`stat_translations/stat_descriptions.json`.",
          ["name", "metadata", "required level", "type", "martial slots", "unique items", "jewellery", "corrupted/sanctified", "stats per category"], rows)

    # 5. Vaal temple benches
    rows = [[row["Id"], row["Name"], base_name.get(one(row["BaseItemType"]), ""), row["Description"], row["CanTakeCurrency"]]
            for row in table("Incursion2Crafting")]
    write("temple-benches", "Temple of Atziri (Incursion 2) crafting rooms",
          "Table `Incursion2Crafting`: each crafting room of the Vaal temple and the currency it holds.",
          ["id", "room", "currency item", "description", "takes currency"], rows)

    # 6. Recombinable classes
    rows = [[classes.get(int(row["Id"]), row["Id"]), base_name.get(int(row["Currency"]), row["Currency"]), row["i32_32"]]
            for row in table("RecombinableClasses")]
    write("recombinable-classes", "Item classes a recombinator takes",
          "Table `RecombinableClasses`: the item class and the currency item a recombination costs.",
          ["item class", "currency", "i32_32"], rows)

    # 7. Verisium crafts
    rows = [[base_name.get(int(row["OriginalBaseType"]), row["OriginalBaseType"]), row["UniqueName"],
             base_name.get(int(row["NewBaseType"]), row["NewBaseType"]),
             ", ".join(base_name.get(i, str(i)) for i in ids(row["CraftingItem"])), row["CraftingItemCount"], row["i32_112"], row["NewUniqueName"]]
            for row in table("Expedition2VerisiumCrafts")]
    write("verisium-crafts", "Verisium crafts (Expedition, Runes of Aldur)",
          "Table `Expedition2VerisiumCrafts`: a base turned into another base with Verisium.",
          ["original base", "unique name row", "new base", "crafting item", "count", "i32_112", "new unique name"], rows)

    # 8. Currency exchange categories
    rows = []
    exchange_categories = {int(row["rownum"]): row.get("Name") or row.get("Id") for row in table("CurrencyExchangeCategories")}
    for row in table("CurrencyExchange"):
        rows.append([base_name.get(int(row["Item"]), row["Item"]) if "Item" in row else row[list(row)[1]],
                     exchange_categories.get(one(row.get("Category", "")), row.get("Category", ""))])
    write("currency-exchange", "Items on the in-game Currency Exchange", "Table `CurrencyExchange`.", ["item", "category"], rows)

    # 9. Modifier census per item class
    base_items = json.loads((folder() / "base_items.json").read_text(encoding="utf-8"))
    class_tags = defaultdict(Counter)
    for record in base_items.values():
        if record.get("domain") == "item" and record.get("release_state") == "released":
            class_tags[record["item_class"]].update(record.get("tags", []))
    rows = []
    for item_class, tags in sorted(class_tags.items()):
        tagset = set(tags)
        counts = Counter()
        families = defaultdict(set)
        for key, mod in repoe_mods.items():
            if mod["domain"] not in ("item", "desecrated") or mod["generation_type"] not in ("prefix", "suffix"):
                continue
            for weight in mod["spawn_weights"]:
                if weight["tag"] in tagset:
                    if weight["weight"] > 0:
                        side = f"{mod['domain']} {mod['generation_type']}"
                        counts[side] += 1
                        families[side].add(mod["type"])
                    break
        if counts:
            rows.append([item_class, len(tags and [1] or []) and sum(1 for r in base_items.values() if r["item_class"] == item_class and r.get("release_state") == "released"),
                         *(f"{counts[s]} / {len(families[s])}" for s in ("item prefix", "item suffix", "desecrated prefix", "desecrated suffix"))])
    write("mod-census", "Modifier census per item class (mods / mod types that can spawn)",
          "From `mods.json` and `base_items.json` (domain `item` and `desecrated`): a mod counts for a class when the first spawn tag "
          "of the mod that any released base of the class carries has a positive weight (the game's first-match rule, as in PoE1). "
          "Every positive weight in the PoE2 export is 1: the real weights are not in the client data.",
          ["item class", "released bases", "prefixes", "suffixes", "desecrated prefixes", "desecrated suffixes"], rows)


if __name__ == "__main__":
    main()
